DO $schema$ BEGIN
CREATE SCHEMA progresso_gang;
REVOKE ALL ON SCHEMA progresso_gang FROM PUBLIC, anon, authenticated;
PERFORM set_config('search_path','progresso_gang, pg_catalog',true);
CREATE TABLE users (id text PRIMARY KEY, username text NOT NULL, username_key text NOT NULL UNIQUE, password_hash text, role text NOT NULL CHECK(role IN ('admin','member')), is_owner integer NOT NULL DEFAULT 0, active integer NOT NULL DEFAULT 1, created_at bigint NOT NULL);
CREATE TABLE sessions (token_hash text PRIMARY KEY, user_id text NOT NULL REFERENCES users(id), csrf text NOT NULL, expires_at bigint NOT NULL);
CREATE INDEX sessions_user_id_idx ON sessions(user_id);
CREATE TABLE invites (token_hash text PRIMARY KEY, expires_at bigint NOT NULL, used integer NOT NULL DEFAULT 0);
CREATE TABLE owner_setup (id integer PRIMARY KEY CHECK(id=1), token_hash text NOT NULL, expires_at bigint NOT NULL);
CREATE TABLE channels (id text NOT NULL, kind text NOT NULL CHECK(kind IN ('text','voice')), name text NOT NULL, hint text NOT NULL DEFAULT '', position bigint NOT NULL DEFAULT 0, PRIMARY KEY(id,kind));
CREATE TABLE site_settings (id integer PRIMARY KEY CHECK(id=1), name text NOT NULL, tagline text NOT NULL);
CREATE TABLE messages (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, client_id text NOT NULL UNIQUE, name text NOT NULL, text text NOT NULL, timestamp bigint NOT NULL, channel text NOT NULL DEFAULT 'general', user_id text REFERENCES users(id), deleted_at bigint);
CREATE INDEX messages_channel_id ON messages(channel,id);
CREATE INDEX messages_user_id_idx ON messages(user_id);
CREATE TABLE attachments (id text PRIMARY KEY, request_hash text NOT NULL, mime text NOT NULL, width integer NOT NULL, height integer NOT NULL, size bigint NOT NULL, animated integer NOT NULL, data bytea NOT NULL, created_at bigint NOT NULL, owner_id text REFERENCES users(id));
CREATE INDEX attachments_owner_id_idx ON attachments(owner_id);
CREATE TABLE message_attachments (message_id bigint NOT NULL REFERENCES messages(id), attachment_id text NOT NULL UNIQUE REFERENCES attachments(id), position integer NOT NULL, PRIMARY KEY(message_id,attachment_id));
CREATE TABLE profiles (user_id text PRIMARY KEY, description text NOT NULL DEFAULT '', avatar_id text REFERENCES attachments(id));
CREATE INDEX profiles_avatar_id_idx ON profiles(avatar_id);
CREATE TABLE soundboard (id text PRIMARY KEY, channel text NOT NULL, name text NOT NULL, owner_id text NOT NULL, data bytea NOT NULL, created_at bigint NOT NULL);
CREATE TABLE message_events (seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, message_id bigint NOT NULL, channel text NOT NULL, kind text NOT NULL, UNIQUE(message_id,kind));
CREATE INDEX message_events_channel_seq ON message_events(channel,seq);
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE invites ENABLE ROW LEVEL SECURITY;
ALTER TABLE owner_setup ENABLE ROW LEVEL SECURITY;
ALTER TABLE channels ENABLE ROW LEVEL SECURITY;
ALTER TABLE site_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE attachments ENABLE ROW LEVEL SECURITY;
ALTER TABLE message_attachments ENABLE ROW LEVEL SECURITY;
ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE soundboard ENABLE ROW LEVEL SECURITY;
ALTER TABLE message_events ENABLE ROW LEVEL SECURITY;
END $schema$;
